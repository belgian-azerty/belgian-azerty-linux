#!/usr/bin/env python3
# Generate the "mac" section of xkb/symbols/be_capslock (option be_azerty:mac): the Belgian Apple (Mac) layout, read
# from Unicode CLDR's open keyboard data (release 43, keyboards/osx/fr-BE-t-k0-osx.xml; the nl-BE and de-BE files
# are identical). Option is the AltGr level, as in Linux's own "(Macintosh)" variants.
#   python3 tools/gen_mac_symbols.py CLDR_OSX_XML > section.txt
# CLDR names the two ISO keys by Apple's key codes, which are swapped on Apple ISO keyboards: its E00 (left of 1) is
# the key next to left Shift on the keyboard, and the other way round. The section uses the physical place, as
# Linux's fr(mac) does: @ # left of 1, < > next to left Shift.
import ctypes, re, sys, xml.etree.ElementTree as ET
L = ctypes.CDLL("libxkbcommon.so.0")
L.xkb_utf32_to_keysym.restype = ctypes.c_uint32; L.xkb_utf32_to_keysym.argtypes = [ctypes.c_uint32]
L.xkb_keysym_get_name.argtypes = [ctypes.c_uint32, ctypes.c_char_p, ctypes.c_size_t]
DEAD = {'´': 'dead_acute', '`': 'dead_grave', '^': 'dead_circumflex', '¨': 'dead_diaeresis', '~': 'dead_tilde'}
# Option on a Mac: the "opt" modifier; Linux's AltGr level (right Option on an Apple keyboard).
STATES = {'base': set(), 'shift': {'shift'}, 'opt': {'opt'}, 'shiftopt': {'opt', 'shift'}}
def matches(attr, want):
    if attr is None: return not want
    for alt in attr.split():
        req = set(); opt = set()
        for m in alt.split('+'):
            m = re.sub(r'[LR](\??)$', r'\1', m) if m[:-1] in ('opt', 'shift', 'ctrl', 'cmd') or m[:-2] in ('opt', 'shift', 'ctrl', 'cmd') else m
            (opt if m.endswith('?') else req).add(m.rstrip('?'))
        if req <= want <= req | opt: return True
    return False
def unesc(s): return re.sub(r'\\u\{([0-9a-fA-F]+)\}', lambda m: chr(int(m.group(1), 16)), s)
ISO = {'E00': 'LSGT', 'B00': 'TLDE', 'C12': 'BKSL', 'D13': 'BKSL', 'A03': 'SPCE'}      # E00/B00: see the note above
for i in range(1, 13): ISO['E%02d' % i] = 'AE%02d' % i; ISO['D%02d' % i] = 'AD%02d' % i
for i in range(1, 12): ISO['C%02d' % i] = 'AC%02d' % i
for i in range(1, 11): ISO['B%02d' % i] = 'AB%02d' % i
root = ET.parse(sys.argv[1]).getroot()
deadc = {unesc(t.get('from'))[0] for t in root.iter('transform') if len(unesc(t.get('from'))) >= 2}
buf = ctypes.create_string_buffer(64)
def sym(ch, transform):
    if ch is None: return 'NoSymbol'
    if ch in deadc and transform != 'no' and ch in DEAD: return DEAD[ch]
    if len(ch) != 1 or 0xe000 <= ord(ch) <= 0xf8ff: return 'VoidSymbol'     # strings, Apple logo (private use)
    ks = L.xkb_utf32_to_keysym(ord(ch)); L.xkb_keysym_get_name(ks, buf, 64); return buf.value.decode()
keys = {}
for st, want in STATES.items():
    km = next(k for k in root.findall('keyMap') if matches(k.get('modifiers'), want))
    for m in km.findall('map'):
        k = ISO.get(m.get('iso'))
        if k: keys.setdefault(k, {})[st] = sym(unesc(m.get('to')), m.get('transform'))
order = ['TLDE'] + ['AE%02d' % i for i in range(1, 13)] + ['AD%02d' % i for i in range(1, 13)] + \
        ['AC%02d' % i for i in range(1, 12)] + ['BKSL', 'LSGT'] + ['AB%02d' % i for i in range(1, 11)] + ['SPCE']
print('// Generated by tools/gen_mac_symbols.py from Unicode CLDR 43 keyboards/osx/fr-BE-t-k0-osx.xml ("Belgian").')
print('// CLDR data: Copyright (c) Unicode, Inc., Unicode License v3 (https://www.unicode.org/license.txt).')
print('hidden partial alphanumeric_keys')
print('xkb_symbols "mac" {')
for k in order:
    if k not in keys: continue
    v = keys[k]
    print('    key <%s> { [ %s ] };' % (k, ', '.join(v.get(s, 'NoSymbol') for s in STATES)))
print('};')
