#!/usr/bin/env python3
# Accent then Space for the world prototype: for every layout of the table, every accent key of the new layout and
# what Windows types for "accent then Space" (Unicode CLDR 43), next to what Linux's own accent table (Compose,
# en_US.UTF-8) types. world-keyboard-windows accent-space reads this table and writes a per-user ~/.XCompose with the
# lines where Windows differs, for the layouts that user has.
#   python3 -I world/tools/gen_accent_space.py world/layouts.tsv world/cldr-43 world/xkb OUT.tsv
# Columns: id (as desktops name it: layout, or layout+variant), keysym, windows, linux, line (the Compose line that
# makes Windows's result; the command writes it only where windows and linux differ)
import csv, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import winkb

def table(tab, cldrdir, xkbdir):
    rows = list(csv.DictReader(open(tab, encoding='utf-8'), delimiter='\t'))
    ctx = winkb.context(xkbdir); out = []
    for r in rows:
        name, keys, trans = winkb.read_cldr(os.path.join(cldrdir, r['cldr_file']))
        kb = winkb.Keymap(ctx, r['out_layout'], r['out_variant'])
        if not kb.ok(): sys.exit(f"cannot load {r['out_layout']}({r['out_variant']})")
        lid = r['out_layout'] if r['out_variant'] == 'basic' else f"{r['out_layout']}+{r['out_variant']}"
        seen = {}
        for k, ks in keys.items():
            for st in winkb.STATES:
                w = ks.get(st) or ''
                if not w.startswith('dead:'): continue
                sym = kb.press_sym(st, k)
                if not (winkb.sym_char(sym) or '').startswith('dead:'): continue   # Linux keeps a plain key here
                to = trans.get(w[5:] + ' ')
                if to is None: continue
                n = winkb.sym_name(sym)
                if n in seen and seen[n] != to: sys.exit(f'{lid}: {n} then Space gives two different results on Windows')
                seen[n] = to
        for n, to in sorted(seen.items()):
            lin = winkb.compose_syms(winkb.L.xkb_keysym_from_name(n.encode(), 0), winkb.L.xkb_keysym_from_name(b'space', 0))
            esc = to.replace('\\', '\\\\').replace('"', '\\"')
            out.append((lid, n, to, lin or '', f'<{n}> <space> : "{esc}" {winkb.char_to_sym(to) or ""}'.rstrip()))
    return out

if __name__ == '__main__':
    tab, cldr, xkb, dest = sys.argv[1:5]
    t = table(tab, cldr, xkb)
    with open(dest, 'w', encoding='utf-8') as f:
        f.write('# world-keyboard-windows: accent then Space, Windows (CLDR 43) and Linux (Compose en_US.UTF-8). '
                'Generated by world/tools/gen_accent_space.py; do not edit by hand.\n')
        f.write('id\tkeysym\twindows\tlinux\tline\n')
        for row in t: f.write('\t'.join(row) + '\n')
    diff = [x for x in t if x[2] != x[3]]
    print(f'{len(t)} accent keys over {len({x[0] for x in t})} layouts; Windows differs from Linux on {len(diff)}:',
          ', '.join(sorted({f"{x[1]} -> {x[2]}" for x in diff})))
